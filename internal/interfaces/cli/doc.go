// Package cli предоставляет интерфейс командной строки для клиента GophKeeper.
//
// Этот пакет реализует CLI приложение с использованием библиотеки Cobra,
// предоставляя пользователю команды для работы с системой хранения паролей.
//
// Основные команды:
//   - register: регистрация нового пользователя
//   - login: вход в систему
//   - logout: выход из системы
//   - add: добавление различных типов данных (логин/пароль, карта, текст, файл)
//   - list: просмотр списка сохраненных данных
//   - get: получение конкретного элемента данных
//   - delete: удаление элемента данных
//   - sync: синхронизация данных с сервером
//
// Пример использования:
//
//	rootCmd := cli.NewRootCommand()
//	if err := rootCmd.Execute(); err != nil {
//	    log.Fatal(err)
//	}
